#!/usr/bin/env python3
"""
youtube_scan.py – YouTube-Kanäle scannen, Videos nach Schmiedetechnik taggen,
Kanal- und Videoseiten (DE/EN) für das Quartz-Wiki erzeugen.

Scan YouTube channels, tag videos by forging technique and generate
channel/video pages (DE/EN) for the Quartz wiki.

Benutzung / usage
-----------------
  # 1) Nur Seiten aus dem Cache (data/videos/*.json) neu erzeugen:
  python3 scripts/youtube_scan.py

  # 2) Videodaten frisch von der YouTube Data API v3 holen:
  export YOUTUBE_API_KEY=...        # Google-Cloud-API-Schlüssel (YouTube Data API v3)
  python3 scripts/youtube_scan.py --fetch

  # 3) Eigene Abos nach Schmiede-Kanälen durchsuchen
  #    a) Abos öffentlich + Kanal-ID:
  python3 scripts/youtube_scan.py --subscriptions UCxxxxxxxxxxxxxxxxxxxxxx
  #    b) Google-Takeout-Export (YouTube › Abos › subscriptions.csv):
  python3 scripts/youtube_scan.py --takeout path/to/subscriptions.csv

Ergebnis der Abo-Suche: data/subscriptions.json + Seiten de/kanaele/abos.md, en/channels/subscriptions.md.
Gefundene Kanäle können in data/channels.json übernommen werden.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
CONTENT = ROOT / "content"
API = "https://www.googleapis.com/youtube/v3/"

FORGE_RX = re.compile(
    r"blacksmith|forge|forging|schmied|schmiede|smed|smide|anvil|amboss|bladesmith|"
    r"knife ?mak|axe|ironwork|metalsmith|hammer|damascus|damast|farrier|hufschmied",
    re.I,
)
TUTORIAL_RX = re.compile(
    r"how|basic|begin|tutorial|lesson|tip|technique|learn|level|fundamental|101|explained|"
    r"guide|getting started|instruction|theory|anleitung|grundlagen",
    re.I,
)

GENERATED_NOTE_DE = "> [!info] Automatisch erzeugt\n> Diese Seite wird von `scripts/youtube_scan.py` aus den YouTube-Metadaten erzeugt. Änderungen bitte in `data/channels.json` bzw. `data/topics.json` vornehmen.\n"
GENERATED_NOTE_EN = "> [!info] Auto-generated\n> This page is generated by `scripts/youtube_scan.py` from YouTube metadata. Edit `data/channels.json` or `data/topics.json` instead.\n"


# --------------------------------------------------------------------------- API
def api(endpoint: str, **params):
    key = os.environ.get("YOUTUBE_API_KEY")
    if key:
        params["key"] = key
    url = API + endpoint + "?" + urllib.parse.urlencode(params)
    with urllib.request.urlopen(url, timeout=30) as r:
        return json.load(r)


def fetch_channel(cid: str) -> dict:
    c = api("channels", part="snippet,statistics,contentDetails", id=cid)["items"][0]
    uploads = c["contentDetails"]["relatedPlaylists"]["uploads"]
    ids, tok = [], None
    while True:
        p = dict(part="contentDetails", playlistId=uploads, maxResults=50)
        if tok:
            p["pageToken"] = tok
        d = api("playlistItems", **p)
        ids += [i["contentDetails"]["videoId"] for i in d["items"]]
        tok = d.get("nextPageToken")
        if not tok:
            break
    videos = []
    for k in range(0, len(ids), 50):
        d = api("videos", part="snippet,contentDetails,statistics", id=",".join(ids[k : k + 50]))
        for v in d["items"]:
            s = v["snippet"]
            videos.append(
                dict(
                    id=v["id"],
                    title=s["title"],
                    date=s["publishedAt"][:10],
                    dur=v["contentDetails"]["duration"],
                    views=int(v["statistics"].get("viewCount", 0)),
                    desc=s.get("description", "")[:400],
                )
            )
    return dict(
        id=cid,
        title=c["snippet"]["title"],
        handle=c["snippet"].get("customUrl"),
        country=c["snippet"].get("country"),
        subs=int(c["statistics"].get("subscriberCount", 0)),
        videos=videos,
    )


# --------------------------------------------------------------------------- helpers
def seconds(iso: str) -> int:
    m = re.match(r"P(?:(\d+)D)?T?(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?", iso or "")
    if not m:
        return 0
    d, h, mi, s = (int(x or 0) for x in m.groups())
    return d * 86400 + h * 3600 + mi * 60 + s


def fmt_dur(iso: str) -> str:
    s = seconds(iso)
    h, rem = divmod(s, 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m}:{s:02d}"


def md_escape(t: str) -> str:
    # "#" würde von Quartz als Tag gelesen → vollbreites Zeichen
    return t.replace("|", "／").replace("[", "(").replace("]", ")").replace("#", "＃")


def yt(vid: str) -> str:
    return f"https://www.youtube.com/watch?v={vid}"


def load_topics():
    T = json.load(open(DATA / "topics.json", encoding="utf-8"))["topics"]
    for t in T:
        t["rx"] = [re.compile(k, re.I) for k in t["keywords"]]
    return T


def tag(videos, topics):
    for v in videos:
        v["topics"] = [t["id"] for t in topics if any(r.search(v["title"]) for r in t["rx"])]
        v["tutorial"] = bool(TUTORIAL_RX.search(v["title"]))
        v["short"] = seconds(v["dur"]) <= 75 or "#shorts" in v["title"].lower()


def rank(v):
    return (0 if v["tutorial"] else 1, -v["views"])


def write(path: Path, text: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


# --------------------------------------------------------------------------- pages
def video_line(v, channel_name=None):
    who = f" — *{channel_name}*" if channel_name else ""
    return f"- [{md_escape(v['title'])}]({yt(v['id'])}){who} · {v['date'][:4]} · {fmt_dur(v['dur'])}"


def channel_page(ch, data, topics, lang):
    de = lang == "de"
    slug = ch["slug"]
    vids = [v for v in data["videos"] if not v["short"]]
    tagged = [v for v in vids if v["topics"]]
    tr = f"en/channels/{slug}" if de else f"de/kanaele/{slug}"
    L = []
    L.append("---")
    L.append(f'title: "{ch["name"]}"')
    L.append(f"lang: {lang}")
    L.append(f"translation: {tr}")
    L.append("tags: [kanal, youtube]" if de else "tags: [channel, youtube]")
    L.append("---")
    L.append(GENERATED_NOTE_DE if de else GENERATED_NOTE_EN)
    if ch.get("assumption"):
        L.append(
            "> [!question] Annahme\n> Im Auftrag war von „einem britischen Schmied, der erweiterte Grundtechniken vermittelt“ die Rede. Gemeint ist hier vermutlich Mark Aspery. Falls ein anderer Kanal gemeint war, bitte in `data/channels.json` ergänzen.\n"
            if de
            else "> [!question] Assumption\n> The brief mentioned “a British smith who teaches extended fundamentals”. Mark Aspery is assumed here. If another channel was meant, add it to `data/channels.json`.\n"
        )
    L.append(("| Kanalprofil | |" if de else "| Channel profile | |") + "\n|---|---|")
    L.append(f"| {'Kanal' if de else 'Channel'} | [{ch['name']}](https://www.youtube.com/channel/{ch['id']}) ({data.get('handle') or ''}) |")
    L.append(f"| {'Person' if de else 'Person'} | {ch.get('person','')} |")
    L.append(f"| {'Herkunft' if de else 'Based in'} | {ch.get('origin','')} |")
    L.append(f"| {'Abonnenten' if de else 'Subscribers'} | {data.get('subs', 0):,} |".replace(",", "."))
    L.append(f"| {'Videos gesamt / mit Technikbezug' if de else 'Videos total / technique-related'} | {len(data['videos'])} / {len(tagged)} |")
    L.append("")
    L.append("## " + ("Profil & Lehrschwerpunkt" if de else "Profile & teaching focus"))
    L.append(ch["focus_de"] if de else ch["focus_en"])
    L.append("")
    if ch.get("playlists"):
        L.append("## " + ("Lehr-Playlists" if de else "Teaching playlists"))
        first = ch["playlists"][0]
        L.append(f"![{first[1]}](https://www.youtube.com/playlist?list={first[0]})")
        L.append("")
        for pid, name in ch["playlists"]:
            L.append(f"- [{name}](https://www.youtube.com/playlist?list={pid})")
        L.append("")
    L.append("## " + ("Tutorials nach Technik" if de else "Tutorials by technique"))
    L.append(
        "Auswahl: Titel mit Technikbezug, Lehrvideos zuerst, danach nach Aufrufen; Shorts ausgeblendet. Vollständige Listen je Technik unter [[de/videos/index|Videos nach Technik]]."
        if de
        else "Selection: titles referring to a technique, teaching videos first, then by views; shorts hidden. Full lists per technique under [[en/videos/index|Videos by technique]]."
    )
    L.append("")
    for t in topics:
        vs = sorted([v for v in tagged if t["id"] in v["topics"]], key=rank)
        if not vs:
            continue
        page = t["page_de"] if de else t["page_en"]
        name = t["de"] if de else t["en"]
        L.append(f"### {name}")
        L.append(f"→ [[{page}|{'Artikel' if de else 'Article'}: {name}]]")
        L.append("")
        for v in vs[:12]:
            L.append(video_line(v))
        if len(vs) > 12:
            L.append(f"- … {'weitere' if de else 'more'} {len(vs)-12}")
        L.append("")
    return "\n".join(L) + "\n"


def topic_page(t, alldata, chmap, lang):
    de = lang == "de"
    name = t["de"] if de else t["en"]
    slug_de, slug_en = t["id"], t["slug_en"]
    tr = f"en/videos/{slug_en}" if de else f"de/videos/{slug_de}"
    L = ["---", f'title: "{"Videos" if de else "Videos"}: {name}"', f"lang: {lang}", f"translation: {tr}",
         "tags: [videos, " + t["id"] + "]", "---", GENERATED_NOTE_DE if de else GENERATED_NOTE_EN]
    page = t["page_de"] if de else t["page_en"]
    L.append(("Zugehöriger Artikel: " if de else "Related article: ") + f"[[{page}|{name}]]\n")
    allv = []
    for s, d in alldata.items():
        for v in d["videos"]:
            if t["id"] in v["topics"] and not v["short"]:
                allv.append((s, v))
    allv.sort(key=lambda x: rank(x[1]))
    if allv:
        L.append("## " + ("Top-Lehrvideos" if de else "Top teaching videos"))
        for s, v in allv[:3]:
            L.append(f"**{md_escape(v['title'])}** — *{chmap[s]['name']}*")
            L.append(f"![]({yt(v['id'])})\n")
    for s, d in alldata.items():
        vs = sorted([v for v in d["videos"] if t["id"] in v["topics"] and not v["short"]], key=rank)
        if not vs:
            continue
        cpage = f"de/kanaele/{s}" if de else f"en/channels/{s}"
        L.append(f"## [[{cpage}|{chmap[s]['name']}]] ({len(vs)})")
        for v in vs[:25]:
            L.append(video_line(v))
        if len(vs) > 25:
            L.append(f"- … {'weitere' if de else 'more'} {len(vs)-25}")
        L.append("")
    return "\n".join(L) + "\n"


def index_pages(topics, alldata, chmap):
    for lang in ("de", "en"):
        de = lang == "de"
        L = ["---", f'title: "{"Videos nach Technik" if de else "Videos by technique"}"', f"lang: {lang}",
             f"translation: {'en/videos/index' if de else 'de/videos/index'}", "---",
             GENERATED_NOTE_DE if de else GENERATED_NOTE_EN,
             "| " + ("Technik" if de else "Technique") + " | " + " | ".join(chmap[s]["name"] for s in alldata) + " |",
             "|---|" + "---|" * len(alldata)]
        for t in topics:
            cnt = [sum(1 for v in d["videos"] if t["id"] in v["topics"] and not v["short"]) for d in alldata.values()]
            link = f"[[de/videos/{t['id']}|{t['de']}]]" if de else f"[[en/videos/{t['slug_en']}|{t['en']}]]"
            L.append(f"| {link} | " + " | ".join(str(c) for c in cnt) + " |")
        L.append("")
        L.append("*Zählung über Titel-Stichwörter (siehe `data/topics.json`), ohne Shorts.*" if de else "*Counted via title keywords (see `data/topics.json`), shorts excluded.*")
        write(CONTENT / lang / "videos" / "index.md", "\n".join(L) + "\n")


# --------------------------------------------------------------------------- subscriptions
def subscriptions_from_api(channel_id):
    res, tok = [], None
    while True:
        p = dict(part="snippet", channelId=channel_id, maxResults=50)
        if tok:
            p["pageToken"] = tok
        d = api("subscriptions", **p)
        for i in d["items"]:
            s = i["snippet"]
            res.append(dict(id=s["resourceId"]["channelId"], title=s["title"], desc=s.get("description", "")))
        tok = d.get("nextPageToken")
        if not tok:
            break
    return res


def subscriptions_from_takeout(path):
    res = []
    with open(path, encoding="utf-8-sig") as f:
        for row in csv.reader(f):
            if not row or row[0].lower().startswith(("channel id", "kanal-id", "kanal id")):
                continue
            res.append(dict(id=row[0].strip(), title=row[2].strip() if len(row) > 2 else "", desc=""))
    # Beschreibungen nachladen
    for k in range(0, len(res), 50):
        ids = ",".join(r["id"] for r in res[k : k + 50])
        try:
            d = api("channels", part="snippet", id=ids)
            m = {i["id"]: i["snippet"] for i in d.get("items", [])}
            for r in res[k : k + 50]:
                if r["id"] in m:
                    r["desc"] = m[r["id"]].get("description", "")
                    r["title"] = r["title"] or m[r["id"]]["title"]
        except Exception as e:  # noqa
            print("warn:", e, file=sys.stderr)
    return res


def report_subscriptions(subs, known_ids):
    hits = [s for s in subs if FORGE_RX.search(s["title"] + " " + s["desc"])]
    json.dump(dict(total=len(subs), forging=hits), open(DATA / "subscriptions.json", "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    for lang in ("de", "en"):
        de = lang == "de"
        L = ["---", f'title: "{"Schmiede-Kanäle in meinen Abos" if de else "Forging channels in my subscriptions"}"', f"lang: {lang}",
             f"translation: {'en/channels/subscriptions' if de else 'de/kanaele/abos'}", "---",
             GENERATED_NOTE_DE if de else GENERATED_NOTE_EN,
             (f"{len(subs)} Abos geprüft, {len(hits)} mit Schmiedebezug (Stichwortsuche in Name/Beschreibung)." if de
              else f"{len(subs)} subscriptions checked, {len(hits)} forging-related (keyword match on name/description)."), "",
             "| Kanal | Im Wiki | Beschreibung |" if de else "| Channel | In wiki | Description |", "|---|---|---|"]
        for h in hits:
            inwiki = "✔" if h["id"] in known_ids else ""
            L.append(f"| [{md_escape(h['title'])}](https://www.youtube.com/channel/{h['id']}) | {inwiki} | {md_escape(h['desc'][:140]).replace(chr(10),' ')} |")
        path = CONTENT / "de" / "kanaele" / "abos.md" if de else CONTENT / "en" / "channels" / "subscriptions.md"
        write(path, "\n".join(L) + "\n")
    print(f"subscriptions: {len(subs)} total, {len(hits)} forging-related")


# --------------------------------------------------------------------------- main
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--fetch", action="store_true", help="Videodaten via API aktualisieren")
    ap.add_argument("--subscriptions", metavar="CHANNEL_ID", help="öffentliche Abos dieses Kanals prüfen")
    ap.add_argument("--takeout", metavar="CSV", help="Google-Takeout subscriptions.csv prüfen")
    a = ap.parse_args()

    cfg = json.load(open(DATA / "channels.json", encoding="utf-8"))["channels"]
    chmap = {c["slug"]: c for c in cfg}
    topics = load_topics()
    vdir = DATA / "videos"
    vdir.mkdir(exist_ok=True)

    if a.subscriptions or a.takeout:
        subs = subscriptions_from_api(a.subscriptions) if a.subscriptions else subscriptions_from_takeout(a.takeout)
        report_subscriptions(subs, {c["id"] for c in cfg})

    alldata = {}
    for c in cfg:
        f = vdir / f"{c['slug']}.json"
        if a.fetch or not f.exists():
            print("fetch", c["name"], file=sys.stderr)
            d = fetch_channel(c["id"])
            json.dump(d, open(f, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
        alldata[c["slug"]] = json.load(open(f, encoding="utf-8"))
        tag(alldata[c["slug"]]["videos"], topics)

    for c in cfg:
        d = alldata[c["slug"]]
        write(CONTENT / "de" / "kanaele" / f"{c['slug']}.md", channel_page(c, d, topics, "de"))
        write(CONTENT / "en" / "channels" / f"{c['slug']}.md", channel_page(c, d, topics, "en"))
    for t in topics:
        write(CONTENT / "de" / "videos" / f"{t['id']}.md", topic_page(t, alldata, chmap, "de"))
        write(CONTENT / "en" / "videos" / f"{t['slug_en']}.md", topic_page(t, alldata, chmap, "en"))
    index_pages(topics, alldata, chmap)
    print("ok:", sum(len(d["videos"]) for d in alldata.values()), "videos,", len(cfg), "channels")


if __name__ == "__main__":
    main()
